// Run against pnpm preview; resolve Playwright from a temporary installation.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE);
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const output = process.env.SMOKE_OUTPUT || 'docs/browser-evidence';
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:4173', locale: 'en-US', viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [], responses = [], results = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) responses.push([r.url(), r.status()]); });
  await page.addInitScript(() => {
    window.audioCalls = [];
    const original = HTMLMediaElement.prototype.play;
    HTMLMediaElement.prototype.play = function () {
      window.audioCalls.push({ src: this.src, time: this.currentTime });
      return original.call(this);
    };
  });
  await page.goto('http://127.0.0.1:4173/timer/');
  await page.getByRole('alertdialog').waitFor();
  await page.screenshot({ path: path.join(output, 'tour.png') });
  console.log('TOUR', await page.getByRole('alertdialog').innerText());
  for (let step = 1; step <= 7; step++) {
    await page.getByRole('button', { name: step === 7 ? /last|done|finish/i : /next/i }).click();
    if (step < 7) await page.getByRole('button', { name: /next|last|done|finish/i }).waitFor();
  }
  assert.equal(await page.getByRole('alertdialog').count(), 0);
  await page.evaluate(() => localStorage.removeItem('isFirst'));
  await page.reload();
  await page.getByRole('alertdialog').waitFor();
  await page.getByRole('button', { name: /skip/i }).click();
  results.push('First-use tour traverses all seven steps; Skip dismisses a fresh tour');
  const card = page.locator('.card').first();
  await card.getByRole('button', { name: 'Edit time', exact: true }).click();
  await card.getByLabel('Seconds', { exact: true }).selectOption('12');
  await card.getByLabel('Minutes', { exact: true }).selectOption('0');
  await card.getByRole('button', { name: 'confirm', exact: true }).click();
  assert.equal(await card.getByRole('timer').getAttribute('aria-label'), '0h 0m 12s');
  await card.getByLabel('timer name', { exact: true }).fill('Integration countdown');
  await card.getByRole('button', { name: 'start', exact: true }).click();
  await page.waitForTimeout(2200);
  await card.getByRole('button', { name: 'pause', exact: true }).click();
  const paused = await card.getByRole('timer').getAttribute('aria-label');
  await page.waitForTimeout(1200);
  assert.equal(await card.getByRole('timer').getAttribute('aria-label'), paused);
  await card.getByRole('button', { name: 'resume', exact: true }).click();
  await page.waitForTimeout(1100);
  assert.notEqual(await card.getByRole('timer').getAttribute('aria-label'), paused);
  await card.getByRole('button', { name: 'reset', exact: true }).click();
  assert.equal(await card.getByRole('timer').getAttribute('aria-label'), '0h 0m 12s');
  results.push('Countdown edits, starts, pauses, resumes and resets to configured duration');
  await page.locator('.timer-add summary').click();
  await page.getByRole('button', { name: 'Stopwatch', exact: true }).click({ timeout: 5000 });
  const stopwatch = page.locator('.card').last();
  await stopwatch.getByRole('button', { name: 'start', exact: true }).click();
  await page.waitForTimeout(2100);
  await stopwatch.getByRole('button', { name: 'pause', exact: true }).click();
  assert.notEqual(await stopwatch.getByRole('timer').getAttribute('aria-label'), '0h 0m 0s');
  await stopwatch.getByRole('button', { name: 'resume', exact: true }).click();
  await page.waitForTimeout(1100);
  await stopwatch.getByRole('button', { name: 'reset', exact: true }).click();
  assert.equal(await stopwatch.getByRole('timer').getAttribute('aria-label'), '0h 0m 0s');
  results.push('Stopwatch add/start/pause/resume/reset');
  await page.locator('.timer-theme summary').click();
  await page.getByRole('button', { name: 'winter', exact: true }).click({ timeout: 5000 });
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'winter');
  await page.reload();
  assert.equal(await card.getByLabel('timer name', { exact: true }).inputValue(), 'Integration countdown');
  assert.equal(await card.getByRole('timer').getAttribute('aria-label'), '0h 0m 12s');
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'winter');
  assert.equal(await page.getByRole('alertdialog').count(), 0);
  results.push('Reload preserves timer title/duration/types, theme and dismissed tour');
  await stopwatch.getByRole('button', { name: 'delete timer', exact: true }).click();
  assert.equal(await page.locator('.card').count(), 1);
  await page.locator('.timer-add summary').click();
  await page.getByRole('button', { name: 'Countdown', exact: true }).click();
  assert.equal(await page.locator('.card').count(), 2);
  await page.locator('.card').last().getByRole('button', { name: 'delete timer', exact: true }).click();
  results.push('Countdown add/delete and stopwatch delete');
  await card.getByRole('button', { name: 'Edit time', exact: true }).click();
  await card.getByLabel('Seconds', { exact: true }).selectOption('1');
  await card.getByRole('button', { name: 'confirm', exact: true }).click();
  await card.getByRole('button', { name: 'start', exact: true }).click();
  await page.waitForTimeout(2200);
  assert.equal(await card.getByRole('timer').getAttribute('aria-label'), '0h 0m 0s');
  const audio = await page.evaluate(() => ({ calls: window.audioCalls, sources: [...document.querySelectorAll('audio')].map(a => ({ src: a.src, readyState: a.readyState, error: a.error?.code })) }));
  assert.equal(audio.calls.filter(a => a.src.endsWith('timeUpSound.mp3')).length, 1);
  assert.ok(audio.calls.every(a => a.time === 0));
  assert.ok(audio.sources.every(a => a.src.includes('/timer/') && !a.error && a.readyState >= 2));
  results.push('Countdown expires at zero with one alarm; audio assets load under /timer/ and click playback resets');
  await page.screenshot({ path: path.join(output, 'desktop.png') });
  await page.evaluate(() => localStorage.setItem('timerList', JSON.stringify([
    { type: 'countdown', title: 'Old strings', timerValue: { hours: '1', minutes: '2', seconds: '3' } },
    { type: 'countdown', title: 'Old numbers', timerValue: { hours: 0, minutes: 0, seconds: 12 } },
    { type: 'stopwatch', title: 'Old stopwatch' }
  ])));
  await page.reload();
  assert.equal(await page.locator('.card').count(), 3);
  assert.equal(await card.getByRole('timer').getAttribute('aria-label'), '1h 2m 3s');
  await card.getByRole('button', { name: 'start', exact: true }).focus();
  await page.keyboard.press('Enter');
  await page.waitForTimeout(1100);
  await card.getByRole('button', { name: 'pause', exact: true }).focus();
  await page.keyboard.press('Space');
  assert.notEqual(await card.getByRole('timer').getAttribute('aria-label'), '1h 2m 3s');
  await card.getByRole('button', { name: 'reset', exact: true }).click();
  await card.getByRole('button', { name: 'Edit time', exact: true }).click();
  await card.getByRole('button', { name: 'confirm', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.timerList)[0].timerValue), { hours: 1, minutes: 2, seconds: 3 });
  results.push('Pre-migration raw timerList numeric strings/numbers and stopwatch hydrate; editing writes numbers');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.timer-theme summary').click();
  await page.getByRole('button', { name: 'winter', exact: true }).click({ timeout: 5000 });
  await page.locator('.timer-theme summary').click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: path.join(output, 'mobile.png') });
  const overflow = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
  assert.ok(overflow.scrollWidth <= overflow.width, JSON.stringify(overflow));
  await page.setViewportSize({ width: 320, height: 844 });
  await page.waitForTimeout(1500);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile-320.png') });
  results.push('390px mobile theme menu reaches winter without horizontal page overflow');
  const japanese = await browser.newContext({ locale: 'ja', viewport: { width: 320, height: 844 } });
  await japanese.addInitScript(() => localStorage.setItem('isFirst', 'false'));
  const jaPage = await japanese.newPage();
  await jaPage.goto('http://127.0.0.1:4173/timer/');
  await jaPage.waitForTimeout(1500);
  assert.equal(await jaPage.getByRole('button', { name: 'スタート', exact: true }).count(), 1);
  assert.ok(await jaPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await jaPage.screenshot({ path: path.join(output, 'mobile-ja-320.png') });
  await japanese.close();
  results.push('English/Japanese 320px and English 390px layouts fit; Enter/Space controls work with old numeric-string timer');
  const manifestResponse = await page.request.get('/timer/manifest.webmanifest');
  assert.equal(manifestResponse.status(), 200);
  const manifest = await manifestResponse.json();
  const sw = await page.evaluate(async () => { const reg = await navigator.serviceWorker.ready; return { scope: reg.scope, active: reg.active?.scriptURL }; });
  assert.ok(sw.scope.endsWith('/timer/') && sw.active.endsWith('/timer/sw.js'));
  for (const icon of manifest.icons) assert.equal((await page.request.get('/timer/' + icon.src)).status(), 200);
  const precachedAudio = await page.evaluate(async () => {
    const cacheNames = await caches.keys();
    const entries = (await Promise.all(cacheNames.filter(n => n.includes('precache')).map(async n => (await (await caches.open(n)).keys()).map(r => r.url)))).flat();
    return entries.filter(url => /Sound\.mp3/.test(url));
  });
  assert.equal(precachedAudio.length, 2);
  await context.setOffline(true);
  await page.reload();
  assert.equal(await page.locator('.card').count(), 3);
  assert.ok(await page.evaluate(async () => (await fetch('/timer/clickSound.mp3', { cache: 'no-store' })).ok && (await fetch('/timer/timeUpSound.mp3', { cache: 'no-store' })).ok));
  await context.setOffline(false);
  results.push('Manifest/icons/service worker scoped to /timer/; offline reload renders saved cards');
  assert.deepEqual(errors, []);
  assert.deepEqual(responses, []);
  fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ browser: browser.version(), results, audio, manifest, sw, precachedAudio, overflow, errors, responses }, null, 2));
  console.log(JSON.stringify({ browser: browser.version(), results, errors, responses }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
